import assert from "node:assert/strict"
import fs from "node:fs"
import { spawn } from "node:child_process"
import { chromium } from "playwright"

const host = "http://127.0.0.1:4178"
const base = `${host}/warc-instagram-posts/`
const server = spawn("node", ["node_modules/vite/bin/vite.js", "preview", "--host", "127.0.0.1", "--port", "4178", "--strictPort", "--base", "/warc-instagram-posts/"], { stdio: ["ignore", "pipe", "pipe"] })
let serverOutput = ""
server.stdout.on("data", (chunk) => { serverOutput += chunk.toString() })
server.stderr.on("data", (chunk) => { serverOutput += chunk.toString() })
const watchdog = setTimeout(() => { server.kill("SIGTERM"); console.error("Preview browser test exceeded 90 seconds"); process.exit(1) }, 90000)
const browser = await chromium.launch({ timeout: 15000 })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, permissions: ["clipboard-read", "clipboard-write"] })
const failures = []
const checks = []
page.on("pageerror", (error) => failures.push(error.message))
const check = (label) => { checks.push(label); console.log(`PASS ${label}`) }
try {
  for (let attempt = 0; attempt < 60; attempt++) {
    try { if ((await fetch(base)).ok) break } catch {}
    await new Promise((resolve) => setTimeout(resolve, 100))
  }
  assert.equal((await fetch(base)).status, 200, serverOutput)
  await page.goto(base)
  await page.getByRole("heading", { name: /From first enquiry/ }).waitFor()
  check("production GitHub Pages base URL loads homepage")
  await page.screenshot({ path: "evidence/home-desktop.png", fullPage: true })
  await page.getByRole("navigation").getByRole("link", { name: "Instagram Posts" }).click()
  await page.getByRole("heading", { name: "The content collection" }).waitFor()
  const carouselData = JSON.parse(fs.readFileSync("src/data/new-clinic-carousels.json", "utf8"))
  for (const carousel of carouselData.carousels) {
    await page.getByRole("button", { name: `Preview carousel ${carousel.number}: ${carousel.title}`, exact: true }).click()
    assert.equal(await page.locator("#selected-title").innerText(), carousel.title)
    assert.equal(await page.locator(`[id="carousel-${carousel.slug}"] figure`).count(), 6)
    for (const slide of carousel.slides) {
      const response = await fetch(`${base}${slide.path}`)
      assert.equal(response.status, 200)
      assert.match(response.headers.get("content-type"), /image\/png/)
    }
  }
  check("all eight carousels select correctly and all 48 base-prefixed PNG paths resolve")
  await page.getByRole("button", { name: /^Preview carousel 1:/ }).click()
  const zipEvent = page.waitForEvent("download")
  await page.getByRole("link", { name: "Download all 48 PNGs" }).click()
  const zip = await zipEvent
  assert.equal(zip.suggestedFilename(), "warc-new-clinic-carousels.zip")
  assert.equal(await zip.failure(), null)
  const pngEvent = page.waitForEvent("download")
  await page.getByRole("link", { name: "Download slide 1 of Opening week, empty desk", exact: true }).click()
  assert.equal(await (await pngEvent).failure(), null)
  const captionEvent = page.waitForEvent("download")
  await page.getByRole("link", { name: "Download caption", exact: true }).click()
  assert.equal(await (await captionEvent).failure(), null)
  await page.getByRole("button", { name: "Copy caption", exact: true }).click()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), carouselData.carousels[0].caption)
  check("ZIP, native PNG, caption downloads and caption clipboard work")
  await page.screenshot({ path: "evidence/posts-desktop.png", fullPage: true })
  await page.goto(`${base}posts#carousel-protect-the-diary`)
  assert.equal(await page.locator("#selected-title").innerText(), "Protect the diary")
  check("direct carousel deep link survives production base route")
  await page.goto(`${base}outreach`)
  const copy = page.getByRole("button", { name: "Copy personalised message", exact: true })
  assert.equal(await copy.isDisabled(), true)
  await page.getByLabel("Recipient name", { exact: true }).fill("Alex")
  await page.getByLabel("Clinic name", { exact: true }).fill("Sample Clinic")
  await page.getByLabel("Opening month and year", { exact: true }).fill("October 2026")
  await page.getByLabel("Your first name", { exact: true }).fill("Valentin")
  for (const box of await page.locator('input[type="checkbox"]').all()) await box.check()
  assert.equal(await copy.isEnabled(), true)
  await copy.click()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText())
  assert.match(clipboard, /Valentin with Akros Lab \(WARC\)/)
  assert.match(clipboard, /Sample Clinic/)
  assert.doesNotMatch(clipboard, /internal_notes|workflow_instruction|Review complete/)
  check("DM default blocked; documented checks unlock public-only personalised clipboard")
  await page.getByRole("button", { name: /Gentle follow-up/ }).click()
  assert.equal(await copy.isDisabled(), true)
  for (const box of await page.locator('input[type="checkbox"]').all()) await box.check()
  assert.equal(await copy.isEnabled(), true)
  await page.getByRole("checkbox", { name: /Original eligibility still valid/ }).uncheck()
  assert.equal(await copy.isDisabled(), true)
  check("changing templates resets checks; follow-ups require original eligibility")
  await page.getByLabel("Channel", { exact: true }).selectOption("email")
  assert.equal(await copy.isDisabled(), true)
  for (const box of await page.locator('input[type="checkbox"]').all()) await box.check()
  assert.equal(await copy.isEnabled(), true)
  await copy.click()
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /30-minute/)
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /reply stop/)
  check("email has separate operator/subscriber checks and honest 30-minute CTA")
  await page.getByLabel("Recipient region", { exact: true }).selectOption("spain")
  assert.equal(await copy.isDisabled(), true)
  for (const box of await page.locator('input[type="checkbox"]').all()) await box.check()
  assert.equal(await copy.isEnabled(), true)
  await page.getByRole("button", { name: /New-clinic opener/ }).click()
  for (const box of await page.locator('input[type="checkbox"]').all()) await box.check()
  assert.equal(await copy.isDisabled(), true)
  check("Spain inbound can be checked; cold templates remain blocked")
  await page.reload()
  assert.equal(await copy.isDisabled(), true)
  check("reload does not persist eligibility or personalisation")
  await page.screenshot({ path: "evidence/outreach-desktop.png", fullPage: true })
  await page.getByRole("tab", { name: "Prospect research" }).click()
  assert.equal(await page.locator("article").count(), 2)
  await page.getByRole("button", { name: "3 unconfirmed / planned", exact: true }).click()
  assert.equal(await page.locator("article").count(), 3)
  assert.match(await page.locator("article").filter({ hasText: "8to8 Dental Elgin" }).innerText(), /no cited source confirms actual opening/)
  await page.getByRole("button", { name: "6 historical", exact: true }).click()
  assert.equal(await page.locator("article").count(), 6)
  check("prospect filters accurately separate 2 confirmed, 3 unconfirmed and 6 historical")
  const exported = await fetch(`${base}outreach/warc-outreach-templates.json`)
  assert.equal(exported.status, 200)
  assert.doesNotMatch(JSON.stringify((await exported.json()).templates), /internal_notes|workflow_instruction/)
  check("JSON exports resolve under Pages base and separate recipient bodies from internal notes")
  await page.getByRole("tab", { name: "Sender & workflow" }).click()
  const cal = await page.getByRole("link", { name: "Open the WARC booking page" }).getAttribute("href")
  assert.equal(cal, "https://cal.com/akroslab-uatcyn/whatsapp24-7receptionistmeeting")
  assert.ok(!cal.includes("?"))
  check("bare Cal.com link has no PII URL prefill")
  for (const route of ["", "posts", "outreach", "archive"]) {
    await page.setViewportSize({ width: 360, height: 800 })
    await page.goto(`${base}${route}`)
    await page.locator("h1").waitFor()
    const dimensions = await page.evaluate(() => ({ document: document.documentElement.scrollWidth, viewport: window.innerWidth }))
    assert.ok(dimensions.document <= dimensions.viewport + 1, `${route || "home"} overflow: ${JSON.stringify(dimensions)}`)
    await page.screenshot({ path: `evidence/${route || "home"}-mobile.png`, fullPage: true })
  }
  check("360px mobile layouts have no horizontal overflow on home, posts, outreach and archive")
  assert.deepEqual(failures, [])
  check("no browser runtime errors")
  fs.writeFileSync("evidence/preview-check-results.json", JSON.stringify({ passed: checks.length, checks, runtimeErrors: failures }, null, 2) + "\n")
} finally {
  await browser.close()
  server.kill("SIGTERM")
  clearTimeout(watchdog)
}
